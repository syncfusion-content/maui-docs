using System.Text.RegularExpressions;

namespace Syncfusion.DotNet.Cli.Core.Licensing;

public sealed record RegistrationResult(string File, bool Updated);

/// <summary>
/// Writes <c>SyncfusionLicenseProvider.RegisterLicense</c> into the startup location each platform requires,
/// before any Syncfusion control is created. Idempotent: a previously generated block is replaced.
/// </summary>
public static class LicenseRegistrar
{
    private const string Marker = "Syncfusion license (generated by 'sfdotnet license activate')";

    // InsertBefore: block goes before the anchor line; otherwise right after the anchor (first statement of the body).
    private sealed record Target(string[] Files, Regex[] Anchors, bool InsertBefore = false);

    private static Target For(string platform, bool vb) => platform switch
    {
        // MauiProgram.CreateMauiApp() - before MauiApp.CreateBuilder().
        "MAUI" => new(["MauiProgram.cs"], [new(@"MauiApp\s+CreateMauiApp\s*\(\s*\)\s*\{")]),
        // Program.cs - before the host builder is created.
        "Blazor" => new(["Program.cs"], [new(@"^[ \t]*(?:var|WebApplicationBuilder|WebAssemblyHostBuilder)\s+\w+\s*=\s*(?:WebApplication\.CreateBuilder|WebAssemblyHostBuilder\.CreateDefault)\(", RegexOptions.Multiline)], true),
        // App constructor / OnStartup - before InitializeComponent or any window is created.
        "WPF" => vb
            ? new(["Application.xaml.vb"], [new(@"Sub\s+New\s*\(\s*\)[^\r\n]*", RegexOptions.IgnoreCase), new(@"Sub\s+OnStartup\s*\([^\r\n]*\)[^\r\n]*", RegexOptions.IgnoreCase)])
            : new(["App.xaml.cs"], [new(@"\bApp\s*\(\s*\)\s*\{"), new(@"void\s+OnStartup\s*\([^)]*\)\s*\{")]),
        "WinUI" => new(["App.xaml.cs"], [new(@"\bApp\s*\(\s*\)\s*\{")]),
        // Program.Main - before ApplicationConfiguration.Initialize / Application.Run.
        "WinForms" => vb
            ? new(["Program.vb", "ApplicationEvents.vb"], [new(@"Sub\s+Main\s*\([^\r\n]*\)[^\r\n]*", RegexOptions.IgnoreCase), new(@"Sub\s+MyApplication_Startup\s*\([^\r\n]*\)[^\r\n]*", RegexOptions.IgnoreCase)])
            : new(["Program.cs"], [new(@"static\s+(?:async\s+)?\w+(?:<[^>]+>)?\s+Main\s*\([^)]*\)\s*\{")]),
        _ => new([], []),
    };

    public static string DescribeLocation(string platform, bool vb) => platform switch
    {
        "MAUI" => "MauiProgram.cs (CreateMauiApp)",
        "Blazor" => "Program.cs (before the host builder)",
        "WPF" => vb ? "Application.xaml.vb" : "App.xaml.cs",
        "WinUI" => "App.xaml.cs (App constructor)",
        "WinForms" => vb ? "Program.vb / ApplicationEvents.vb" : "Program.cs (Main)",
        _ => "project startup file",
    };

    public static RegistrationResult Register(string projectFile, string platform, IReadOnlyList<string> keys)
    {
        var vb = projectFile.EndsWith(".vbproj", StringComparison.OrdinalIgnoreCase);
        var target = For(platform, vb);
        var dir = Path.GetDirectoryName(projectFile)!;
        foreach (var name in target.Files)
        {
            var path = Path.Combine(dir, name);
            if (!File.Exists(path)) continue;
            var source = File.ReadAllText(path);
            var nl = source.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
            var cleaned = Strip(source);
            foreach (var anchor in target.Anchors)
            {
                var m = anchor.Match(cleaned);
                if (!m.Success) continue;
                var lineIndent = IndentOf(cleaned, m.Index);
                string updated;
                if (target.InsertBefore)
                {
                    var lineStart = cleaned.LastIndexOf('\n', Math.Max(0, m.Index - 1)) + 1;
                    updated = cleaned.Insert(m.Index < lineStart ? m.Index : lineStart, Block(keys, vb, lineIndent, nl));
                }
                else
                {
                    var end = m.Index + m.Length;
                    var block = Block(keys, vb, lineIndent + "    ", nl).TrimEnd('\r', '\n');
                    updated = cleaned.Insert(end, nl + block);
                }

                if (updated != source) File.WriteAllText(path, updated);
                return new RegistrationResult(path, updated != source);
            }
        }

        throw new LicenseException(LicenseExitCodes.RegistrationTargetMissing,
            $"Could not find where to register the license. Expected {DescribeLocation(platform, vb)} in {dir}.");
    }

    private static string Block(IReadOnlyList<string> keys, bool vb, string indent, string nl)
    {
        var comment = vb ? "' " : "// ";
        var lines = new List<string> { indent + comment + Marker };
        lines.AddRange(keys.Select(k => $"{indent}Syncfusion.Licensing.SyncfusionLicenseProvider.RegisterLicense(\"{k.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"){(vb ? "" : ";")}"));
        return string.Join(nl, lines) + nl;
    }

    private static string IndentOf(string text, int index)
    {
        var start = text.LastIndexOf('\n', Math.Max(0, index - 1)) + 1;
        return new string(text.Skip(start).TakeWhile(c => c is ' ' or '\t').ToArray());
    }

    /// <summary>Removes a block previously written by this class (marker line plus its RegisterLicense lines).</summary>
    private static string Strip(string source)
        => Regex.Replace(source, @"[ \t]*(?://|')\s*" + Regex.Escape(Marker) + @"[^\r\n]*\r?\n(?:[ \t]*Syncfusion\.Licensing\.SyncfusionLicenseProvider\.RegisterLicense\([^\r\n]*\r?\n)+", "");
}
